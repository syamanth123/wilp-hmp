import { expect, it } from 'vitest';
import { withPlainPlaceholders } from '../importer-placeholder';

const MARK = '(missing — placeholder generated by importer)';

it('a past handout shows plain words wherever the importer left its marker, without changing the original', () => {
  const data = {
    partA: { textBooks: [{ code: 'T1', citation: MARK }], creditUnits: 4 },
    partB: { sessions: [{ topicTitle: `Topic: ${MARK}`, references: [] as string[] }] },
    flag: null,
  };
  const shown = withPlainPlaceholders(data);
  expect(shown.partA.textBooks[0]!.citation).toBe('Not found in the old handout file');
  expect(shown.partB.sessions[0]!.topicTitle).toBe('Topic: Not found in the old handout file');
  expect(shown.partA.creditUnits).toBe(4);
  expect(shown.flag).toBeNull();
  expect(data.partA.textBooks[0]!.citation).toBe(MARK);
});
