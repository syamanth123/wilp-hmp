import { describe, expect, it } from 'vitest';
import type { BitsHandoutV1 } from '@hmp/db';
import { buildChecklistItems, structuredSignals } from './faculty-signals';
import { blankHandoutForRequest } from '../app/faculty/assignments/[id]/structured-editor/state';

// The faculty submission checklist reads handouts written in the new editor
// from their structured data (they have no old-editor text at all), and still
// reads old-editor handouts from their text.

function blank(): BitsHandoutV1 {
  return blankHandoutForRequest({
    courseTitle: 'Business Statistics',
    courseNumbers: ['MBA ZC417'],
    semesterName: 'Sem-I 2026-27',
    instructorName: 'Dr. Example',
  });
}

function complete(): BitsHandoutV1 {
  const h = blank();
  h.partA.courseObjectives = [{ code: 'CO1', description: 'Introduce descriptive statistics' }];
  h.partA.textBooks = [{ code: 'T1', citation: 'Levine, Statistics for Managers, 8th ed.' }];
  h.partB.sessions = [{ ...h.partB.sessions[0]!, topicTitle: 'Collecting and describing data' }];
  h.evaluation.components = [
    {
      ecNumber: 'EC-1',
      subComponents: [
        { name: 'Quizzes', type: 'Online', weight: 30, duration: '' },
        { name: 'Comprehensive', type: 'Open book', weight: 70, duration: '2 hours' },
      ],
    },
  ];
  return h;
}

const done = (structured: ReturnType<typeof structuredSignals> | null, text = '') =>
  buildChecklistItems({
    text,
    versionCount: 1,
    blooms: null,
    coverage: null,
    includeBlooms: false,
    structured,
  }).map((i) => [i.label, i.done] as const);

describe('faculty checklist — structured (new editor) handouts', () => {
  it('a complete handout ticks all 5 items', () => {
    const items = done(structuredSignals(complete()));
    expect(items).toHaveLength(5);
    expect(items.every(([, d]) => d)).toBe(true);
  });

  it('a blank handout ticks only "at least one saved version"', () => {
    const items = done(structuredSignals(blank()));
    expect(items.filter(([, d]) => d).map(([l]) => l)).toEqual(['At least one saved version']);
  });

  it("importer placeholders don't count as content", () => {
    const h = complete();
    h.partA.textBooks = [{ code: 'T1', citation: '(missing — placeholder generated by importer)' }];
    expect(structuredSignals(h).references).toBe(false);
    h.partA.referenceBooks = [{ code: 'R1', citation: 'Anderson, Statistics for Business' }];
    expect(structuredSignals(h).references).toBe(true);
  });

  it('the evaluation item needs weights that add up to 100%', () => {
    const h = complete();
    h.evaluation.components[0]!.subComponents[1]!.weight = 50; // total 80%
    expect(structuredSignals(h).evaluation).toBe(false);
  });

  it('learning outcomes alone count as objectives', () => {
    const h = complete();
    h.partA.courseObjectives = [];
    h.partA.learningOutcomes = [{ code: 'LO1', description: 'Summarise a dataset' }];
    expect(structuredSignals(h).objectives).toBe(true);
  });
});

describe('faculty checklist — legacy (old editor) handouts', () => {
  it('still reads the handout text', () => {
    const text = 'learning objectives. topics covered. evaluation components. textbook references.';
    const items = done(null, text);
    expect(items.every(([, d]) => d)).toBe(true);
  });

  it('empty legacy text ticks only the saved-version item', () => {
    expect(done(null, '').filter(([, d]) => d)).toHaveLength(1);
  });
});
